// Generates src/api/schema.d.ts from openapi.json (the node's /openapi.json, snapshotted in this
// directory; `pnpm sync:api` refreshes it from a running node and a Rust test keeps it honest).
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const spec = JSON.parse(fs.readFileSync(path.join(root, 'openapi.json'), 'utf8'))
const ast = await openapiTS(spec, { emptyObjectsUnknown: true, alphabetize: true })
const out = '// GENERATED by scripts/gen-api.mjs from openapi.json — do not edit.\n' + astToString(ast)
fs.mkdirSync(path.join(root, 'src/api'), { recursive: true })
fs.writeFileSync(path.join(root, 'src/api/schema.d.ts'), out)
const ops = Object.values(spec.paths).reduce((n, p) => n + Object.keys(p).length, 0)
console.log(`gen-api: ${Object.keys(spec.paths).length} paths, ${ops} operations → src/api/schema.d.ts`)
